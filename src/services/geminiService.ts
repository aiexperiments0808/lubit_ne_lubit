// Функции для работы с системным промптом
export const getSystemPrompt = (type: 'default' | 'multiple' = 'default', useDefault = false): string => {
  if (useDefault) {
    return type === 'multiple' ? SYSTEM_PROMPTS.MULTIPLE_CHATS : SYSTEM_PROMPTS.DEFAULT;
  }
  return localStorage.getItem(STORAGE_KEYS.SYSTEM_PROMPT) || SYSTEM_PROMPTS.DEFAULT;
};

export const setSystemPrompt = (prompt: string): void => {
  localStorage.setItem(STORAGE_KEYS.SYSTEM_PROMPT, prompt);
};

